#!/usr/bin/env python3
"""Generate Rakazo built-in Agent Skills from skill folders (CRD hotfix for Rakazo v0.1.6).

  builtin-skills-patch.py <skills_dir> <builtin-skills.ts.orig> <builtin-skills.ts out>

Every <skills_dir>/<name>/SKILL.md becomes a read-only built-in skill visible to every account.
Skills with supporting files (scripts/, references/, assets/) get a short pointer body that tells the
bot to read the full SKILL.md from /opt/crd-skills/<name>/ (baked into the bot computer image);
single-file skills (e.g. skill-installer) embed their body directly.
Called by build-skills.sh.
"""
import json
import re
import sys
from pathlib import Path

BOT_DIR = "/opt/crd-skills"
ANCHOR = "\n];\n\nexport const BUILTIN_AGENT_SKILLS"


def parse(md: str):
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", md, re.S)
    if not m:
        sys.exit("SKILL.md has no frontmatter")
    fm, body = m.group(1), m.group(2)
    fields, key = {}, None
    for line in fm.splitlines():
        km = re.match(r"^([A-Za-z][\w-]*):\s*(.*)$", line)
        if km:
            key = km.group(1)
            fields[key] = [km.group(2)]
        elif key:
            fields[key].append(line)

    def val(k):
        parts = fields.get(k, [""])
        first = parts[0].strip()
        rest = [p.strip() for p in parts[1:] if p.strip()]
        if first in ("|", ">", "|-", ">-", "|+", ">+"):
            first = ""
        return " ".join([first] + rest).strip().strip("'\"")

    return val("name"), val("description"), body.strip() + "\n"


def pointer(name: str) -> str:
    base = f"{BOT_DIR}/{name}"
    return f"""# {name}

ไฟล์ทั้งหมดของ skill นี้ (คำแนะนำฉบับเต็ม, scripts/, references/, assets/) อยู่ที่ `{base}/` (อ่านอย่างเดียว)

ทำตามนี้ทุกครั้งก่อนเริ่มงาน:
1. อ่านคำแนะนำฉบับเต็มด้วย shell: `cat {base}/SKILL.md` แล้วทำตามนั้นทุกขั้น — ข้อความนี้เป็นแค่ตัวชี้ทาง
2. path แบบ relative ในคำแนะนำ (เช่น `scripts/`, `references/`, `assets/`) ให้นับจาก `{base}/`
3. path ของ Windows ในคำแนะนำ (`C:\\`, `D:\\`, `G:\\`, `/mnt/c/`) เป็นตัวอย่างจากเครื่องเดิม — ให้ใช้ไฟล์ที่ผู้ใช้แนบในแชต หรือถามผู้ใช้
4. คำสั่ง PowerShell/Windows ให้แปลงเป็น bash/`python3` ที่เทียบเท่า · ไลบรารี Python ที่มีแล้ว: openpyxl, python-docx, pythainlp, rapidfuzz, matplotlib, PyMuPDF (fitz), ezdxf, shapely
5. ไฟล์ที่ต้องสร้างหรือแก้ ให้คัดลอกไปทำในโฟลเดอร์งานของตัวเอง (โฟลเดอร์ skill แก้ไม่ได้)
6. ผลลัพธ์ที่เป็นไฟล์ (.xlsx/.docx/.pptx/.pdf) ให้แนบในแชตด้วย `attach_file`
"""


def main():
    skills_dir, orig, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    src = orig.read_text(encoding="utf-8")
    if src.count(ANCHOR) != 1:
        sys.exit("anchor not found in builtin-skills.ts.orig")
    entries = []
    for d in sorted(p for p in skills_dir.iterdir() if (p / "SKILL.md").is_file()):
        name, desc, body = parse((d / "SKILL.md").read_text(encoding="utf-8"))
        if name != d.name:
            sys.exit(f"{d}: frontmatter name '{name}' != folder name")
        if not desc or len(name) > 80 or len(desc) > 2000:
            sys.exit(f"{d}: name/description missing or too long")
        has_files = any(p.is_file() and p.name != "SKILL.md" for p in d.rglob("*"))
        entry = {"name": name, "description": desc, "body": pointer(name) if has_files else body}
        entries.append("  " + json.dumps(entry, ensure_ascii=False) + ",")
        print(f"builtin: {name} ({'pointer' if has_files else 'embedded'})")
    head = "\n  // CRD hotfix: skills generated by rakazo/scripts/wsl/builtin-skills-patch.py\n"
    patched = src.replace(ANCHOR, head + "\n".join(entries) + ANCHOR)
    out.write_text("// CRD hotfix (Rakazo v0.1.6): CRD skills as built-ins. Regenerate with build-skills.sh.\n" + patched,
                   encoding="utf-8")


if __name__ == "__main__":
    main()
